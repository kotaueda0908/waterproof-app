export function getTodayQuote(dateStr: string): Quote {
  // 日付をシードにして毎日同じ格言が出るようにする
  let hash = 0
  for (let i = 0; i < dateStr.length; i++) {
    hash = (hash * 31 + dateStr.charCodeAt(i)) >>> 0
  }
  return QUOTES[hash % QUOTES.length]
}
